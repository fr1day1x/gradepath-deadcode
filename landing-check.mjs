import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL||'chrome'});
const page = await browser.newPage({viewport:{width:1440,height:1100}});
page.setDefaultTimeout(15000);
const errors=[];const requests=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(r.method()==='POST'&&r.url().includes('/auth/'))requests.push(r.url())});
await page.goto(process.env.CHECK_URL||'http://127.0.0.1:5173');
await page.getByRole('heading',{name:/Make your\s*next move/}).waitFor();
await page.waitForTimeout(1800);
await page.getByRole('slider',{name:'Preview final exam score'}).fill('98');
await page.getByText('TARGET REACHED',{exact:true}).waitFor();
await page.screenshot({path:'landing-desktop.png',fullPage:true});
await page.getByRole('button',{name:'Sign in to Gradepath'}).click();
assert.equal(await page.locator('#login-email').evaluate(el=>el.validity.valueMissing),true);
await page.getByLabel('Email address').fill('demo@example.com');
await page.getByLabel('Password',{exact:true}).fill('sample-password');
await page.getByRole('button',{name:'Show password'}).click();
assert.equal(await page.locator('#login-password').getAttribute('type'),'text');
await page.getByRole('button',{name:'Hide password'}).click();
await page.getByRole('button',{name:'Explore with sample data'}).click();
await page.getByRole('heading',{name:'Your next move',exact:false}).waitFor();
assert.deepEqual(requests,[],'Guest entry must not transmit credentials');
await page.getByRole('button',{name:'Back to landing'}).click();
await page.getByRole('heading',{name:/Make your\s*next move/}).waitFor();
assert.equal(await page.locator('#login-password').inputValue(),'');
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(600);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.screenshot({path:'landing-mobile.png',fullPage:true});
await page.getByRole('button',{name:'Your workspace'}).click();
assert.equal(await page.locator('#login-email').evaluate(el=>el===document.activeElement),true);
assert.deepEqual(errors,[]);
console.log('PASS: landing, required fields, password toggle, guest entry, no credential transmission, logout, mobile overflow, login focus');
await browser.close();
