import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true, channel:process.env.PLAYWRIGHT_CHANNEL || 'chrome'});
const page = await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173');
await page.getByRole('button',{name:'Explore with sample data'}).click();
await page.getByRole('heading',{name:'Your next move',exact:false}).waitFor();
await page.getByRole('button',{name:'All in'}).click();
await page.getByText('Target unlocked. You’ve got a path.').waitFor();
await page.getByRole('button',{name:'Save this scenario'}).click();
await page.getByRole('heading',{name:'Saved possibilities'}).waitFor();
await page.getByRole('switch',{name:'Replace lowest midterm'}).click();
assert.equal(await page.getByRole('switch',{name:'Replace lowest midterm'}).getAttribute('aria-checked'),'false');
await page.getByRole('button',{name:'Gradebook',exact:true}).click();
await page.getByRole('spinbutton',{name:'Assignments score 1',exact:true}).fill('100');
await page.getByRole('button',{name:'Course policies',exact:true}).click();
await page.getByRole('spinbutton',{name:'Assignments weight'}).fill('30');
assert.equal(await page.getByRole('button',{name:'Apply course policies'}).isDisabled(),true);
await page.getByRole('spinbutton',{name:'Final exam weight'}).fill('25');
await page.getByRole('button',{name:'Apply course policies'}).click();
await page.getByRole('button',{name:'Add course'}).click();
await page.getByRole('textbox',{name:'Course name'}).fill('Psychology');
await page.getByRole('button',{name:'Continue',exact:true}).click();
await page.getByRole('button',{name:'Continue',exact:true}).click();
await page.getByRole('button',{name:'Open my gradebook'}).click();
assert.equal(await page.locator('#course-select option:checked').textContent(),'Psychology');
await page.getByRole('button',{name:'Overview',exact:false}).click();
await page.waitForTimeout(800);
await page.screenshot({path:'desktop-preview.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(500);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Mobile should not overflow horizontally');
await page.screenshot({path:'mobile-preview.png',fullPage:true});
assert.deepEqual(errors,[]);
await page.emulateMedia({reducedMotion:'reduce'});
await page.getByRole('button',{name:'All in'}).click();
await page.waitForTimeout(100);
assert.equal(await page.locator('.confetti').count(),0);
console.log('PASS: scenario, target, saving, switches, grade edits, weight validation, course setup, mobile overflow, reduced motion, no browser errors');
await browser.close();
