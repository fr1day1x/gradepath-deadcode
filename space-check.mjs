await page.getByRole('button',{name:'Explore with sample data'}).click();
await page.getByRole('heading',{name:'Your next move',exact:false}).waitFor();await page.waitForTimeout(1200);
assert.equal(await page.evaluate(()=>scrollY),0);
await page.getByRole('button',{name:'All in'}).click();await page.getByText('Target unlocked. You’ve got a path.').waitFor();
